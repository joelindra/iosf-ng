"""Phase 1: Configuration Profile generator.

Builds a `.mobileconfig` that:
  1. installs the tool's root CA (PayloadType com.apple.security.pkcs1)
  2. optionally includes global proxy (PayloadType com.apple.proxy.http.global - requires Supervised mode)

For standard non-supervised iPhones:
  - CA-only profile installs directly without any Supervised restriction.
  - Proxy is then configured via iPhone Wi-Fi settings (Configure Proxy -> Manual).

Optionally the profile itself can be signed with a developer certificate
(`openssl smime -sign`) so it does not show as "Unsigned Profile".

The profile can be served over HTTP with a QR code for easy on-device
installation (Settings > General > VPN & Device Management).
"""
from __future__ import annotations

import datetime as dt
import hashlib
import ipaddress
import plistlib
import socket
import subprocess
import uuid
from dataclasses import dataclass, field
from pathlib import Path

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, rsa
from cryptography.x509.oid import NameOID


@dataclass
class CertificateBundle:
    ca_key_path: Path
    ca_cert_path: Path
    ca_cert_der: bytes
    ca_cert_pem: bytes
    leaf_cert_path: Path | None = None
    leaf_key_path: Path | None = None
    leaf_cert_der: bytes | None = None

    @property
    def ca_fingerprint_sha256(self) -> str:
        return hashlib.sha256(self.ca_cert_der).hexdigest()


@dataclass
class ProxyConfig:
    host: str
    port: int = 8080
    bypass: list[str] = field(default_factory=lambda: ["*.local", "169.254.0.0/16"])
    username: str | None = None
    password: str | None = None


@dataclass
class ProfileOptions:
    organization: str = "iOSTester"
    display_name: str = "iOSTester CA"
    identifier_prefix: str = "com.iostester"
    proxy: ProxyConfig | None = None
    include_global_proxy: bool = False
    install_ca: bool = True
    install_leaf: bool = True
    description: str = (
        "Generated by iOSTester for AUTHORIZED security testing. Installs the "
        "testing root CA certificate. Remove this profile when testing is complete."
    )


# ---------------------------------------------------------------------------
# certificate authority
# ---------------------------------------------------------------------------

def generate_ca(
    out_dir: Path,
    common_name: str = "iOSTester Root CA",
    organization: str = "iOSTester",
    key_type: str = "rsa",
    validity_days: int = 825,
) -> CertificateBundle:
    out_dir.mkdir(parents=True, exist_ok=True)
    if key_type == "ec":
        key = ec.generate_private_key(ec.SECP256R1())
    else:
        key = rsa.generate_private_key(public_exponent=65537, key_size=2048)

    subject = x509.Name(
        [
            x509.NameAttribute(NameOID.COUNTRY_NAME, "ID"),
            x509.NameAttribute(NameOID.ORGANIZATION_NAME, organization),
            x509.NameAttribute(NameOID.COMMON_NAME, common_name),
        ]
    )
    now = dt.datetime.now(dt.timezone.utc)
    cert = (
        x509.CertificateBuilder()
        .subject_name(subject)
        .issuer_name(subject)
        .public_key(key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now - dt.timedelta(minutes=5))
        .not_valid_after(now + dt.timedelta(days=validity_days))
        .add_extension(x509.BasicConstraints(ca=True, path_length=0), critical=True)
        .add_extension(
            x509.KeyUsage(
                digital_signature=True,
                content_commitment=False,
                key_encipherment=False,
                data_encipherment=False,
                key_agreement=False,
                key_cert_sign=True,
                crl_sign=True,
                encipher_only=False,
                decipher_only=False,
            ),
            critical=True,
        )
        .add_extension(
            x509.SubjectKeyIdentifier.from_public_key(key.public_key()), critical=False
        )
        .sign(key, hashes.SHA256())
    )

    key_path = out_dir / "ca.key.pem"
    cert_path = out_dir / "ca.crt.pem"
    key_path.write_bytes(
        key.private_bytes(
            encoding=serialization.Encoding.PEM,
            format=serialization.PrivateFormat.PKCS8,
            encryption_algorithm=serialization.NoEncryption(),
        )
    )
    cert_path.write_bytes(cert.public_bytes(serialization.Encoding.PEM))
    return CertificateBundle(
        ca_key_path=key_path,
        ca_cert_path=cert_path,
        ca_cert_der=cert.public_bytes(serialization.Encoding.DER),
        ca_cert_pem=cert.public_bytes(serialization.Encoding.PEM),
    )


def load_ca(out_dir: Path) -> CertificateBundle:
    cert_path = out_dir / "ca.crt.pem"
    if not cert_path.exists():
        raise FileNotFoundError(f"No CA found in {out_dir}. Run `iostester profile ca` first.")
    pem = cert_path.read_bytes()
    cert = x509.load_pem_x509_certificate(pem)
    return CertificateBundle(
        ca_key_path=out_dir / "ca.key.pem",
        ca_cert_path=cert_path,
        ca_cert_der=cert.public_bytes(serialization.Encoding.DER),
        ca_cert_pem=pem,
    )


# ---------------------------------------------------------------------------
# mobileconfig building
# ---------------------------------------------------------------------------

def build_mobileconfig(
    ca: CertificateBundle | None,
    options: ProfileOptions,
    out_path: Path,
) -> Path:
    """Assemble the .mobileconfig plist.

    Payload layout:
    * com.apple.security.pkcs1        -> root CA (DER, base64 via plist data)
    * com.apple.security.root         -> root CA as trusted root
    * com.apple.proxy.http.global     -> global proxy settings (ONLY if include_global_proxy=True, requires Supervised)
    """
    out_path.parent.mkdir(parents=True, exist_ok=True)
    top_uuid = str(uuid.uuid4()).upper()
    profile_identifier = f"{options.identifier_prefix}.profile"
    payloads: list[dict] = []

    if options.install_ca:
        if ca is None:
            raise ValueError("install_ca requested but no CA certificate supplied")
        payloads.append(
            {
                "PayloadType": "com.apple.security.pkcs1",
                "PayloadVersion": 1,
                "PayloadIdentifier": f"{profile_identifier}.ca",
                "PayloadUUID": str(uuid.uuid4()).upper(),
                "PayloadDisplayName": "iOSTester Root CA (cert payload)",
                "PayloadDescription": "Installs the testing root CA certificate.",
                "PayloadContent": ca.ca_cert_der,
            }
        )
        payloads.append(
            {
                "PayloadType": "com.apple.security.root",
                "PayloadVersion": 1,
                "PayloadIdentifier": f"{profile_identifier}.root",
                "PayloadUUID": str(uuid.uuid4()).upper(),
                "PayloadDisplayName": "iOSTester Root CA (trusted root)",
                "PayloadDescription": "Adds the testing CA to the trusted root store.",
                "PayloadContent": ca.ca_cert_der,
            }
        )

    # NOTE: Apple limits 'com.apple.proxy.http.global' STRICTLY to Supervised iOS devices.
    # For standard/non-supervised devices, including this payload causes:
    # "Profile Installation Failed: This profile can only be installed on a supervised device".
    if options.include_global_proxy and options.proxy is not None:
        proxy: dict = {
            "HTTPEnable": 1,
            "HTTPProxy": options.proxy.host,
            "HTTPPort": options.proxy.port,
            "HTTPSEnable": 1,
            "HTTPSProxy": options.proxy.host,
            "HTTPSPort": options.proxy.port,
            "ProxyAutoConfigEnable": 0,
            "ProxyCaptiveLoginAllowed": 0,
        }
        if options.proxy.bypass:
            proxy["ExceptionsList"] = list(options.proxy.bypass)
        if options.proxy.username:
            proxy["HTTPProxyUsername"] = options.proxy.username
            proxy["HTTPSProxyUsername"] = options.proxy.username
        payloads.append(
            {
                "PayloadType": "com.apple.proxy.http.global",
                "PayloadVersion": 1,
                "PayloadIdentifier": f"{profile_identifier}.proxy",
                "PayloadUUID": str(uuid.uuid4()).upper(),
                "PayloadDisplayName": "Global HTTP(S) proxy",
                "PayloadDescription": (
                    f"Routes HTTP(S) traffic via {options.proxy.host}:{options.proxy.port}. "
                    "Requires Supervised iOS device."
                ),
                "PayloadContent": proxy,
            }
        )

    top = {
        "PayloadType": "Configuration",
        "PayloadVersion": 1,
        "PayloadIdentifier": profile_identifier,
        "PayloadUUID": top_uuid,
        "PayloadDisplayName": options.display_name,
        "PayloadDescription": options.description,
        "PayloadOrganization": options.organization,
        "PayloadRemovalDisallowed": False,
        "ConsentText": {"Default": options.description},
        "PayloadContent": payloads,
    }

    out_path.write_bytes(plistlib.dumps(top, sort_keys=False))
    return out_path


def sign_mobileconfig(
    path: Path,
    cert_pem: Path,
    key_pem: Path,
    out_path: Path | None = None,
    chain_pem: Path | None = None,
) -> Path:
    """Sign a .mobileconfig using OpenSSL S/MIME (optional, improves credibility)."""
    out = out_path or path.with_suffix(".signed.mobileconfig")
    cmd = [
        "openssl", "smime", "-sign",
        "-signer", str(cert_pem),
        "-inkey", str(key_pem),
        "-nodetach", "-outform", "der",
        "-in", str(path), "-out", str(out),
    ]
    if chain_pem:
        cmd += ["-certfile", str(chain_pem)]
    subprocess.run(cmd, check=True, capture_output=True)
    return out


